"""Synthetic IBSP checks: python -m unittest discover -s tools -p test_bsp2lights.py."""
from contextlib import redirect_stderr, redirect_stdout
import io
from pathlib import Path
import struct
import tempfile
import unittest
import warnings

import bsp2lights


class ExportTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.bsp = self.root / 'SYNTHETIC.bsp'

    def write_bsp(self, entities):
        # A real IBSP header/entity lump exercises bspinfo, without copyrighted assets.
        text = ''.join('{\n' + ''.join('"%s" "%s"\n' % pair for pair in entity.items()) + '}\n'
                       for entity in entities).encode('ascii') + b'\0'
        header_size = 8 + 19 * 8
        header = struct.pack('<4si', b'IBSP', 38)
        header += struct.pack('<ii', header_size, len(text))
        header += struct.pack('<ii', 0, 0) * 18
        self.bsp.write_bytes(header + text)

    def export(self, entities, *options):
        self.write_bsp(entities)
        out = self.root / 'out'
        stdout, stderr = io.StringIO(), io.StringIO()
        with warnings.catch_warnings(), redirect_stdout(stdout), redirect_stderr(stderr):
            # bspinfo's existing reader opens the file without a context manager.
            warnings.simplefilter('ignore', ResourceWarning)
            bsp2lights.main([*options, str(out), str(self.bsp)])
        return (out / 'synthetic.lights').read_text(), stdout.getvalue(), stderr.getvalue()

    @staticmethod
    def light(**keys):
        return {'classname': 'light', 'origin': '1 2 3', **keys}

    @staticmethod
    def rows(text):
        return [line for line in text.splitlines() if line and not line.startswith(('#', 'format'))]

    def test_default_file_is_byte_stable(self):
        text, summary, errors = self.export([
            {'classname': 'worldspawn'}, self.light(style='1'), self.light(style='32'),
            self.light(spawnflags='1'), {'classname': 'light_spot', 'origin': '9 9 9'},
        ])
        self.assertEqual(text.encode('ascii'), (
            '# synthetic: generated by tools/bsp2lights.py from SYNTHETIC.bsp\n'
            '# x y z r g b intensity radius   (intensity = BSP light, radius 0 = from the ini)\n'
            'format raw\n'
            '1.0 2.0 3.0 1.0000 1.0000 1.0000 300 0 style 1\n'
            '1.0 2.0 3.0 1.0000 1.0000 1.0000 300 0\n').encode('ascii'))
        self.assertIn('2 lights (0 spotlights, 1 animated, 1 start-off skipped, 0 suns)', summary)
        self.assertEqual(errors, '')

    def test_legacy_file_is_byte_stable(self):
        text, _, _ = self.export([{'classname': 'worldspawn'},
                                  self.light(light='600', _color='0.25 0.5 1', style='11'),
                                  self.light(spawnflags='1')], '--legacy')
        self.assertEqual(text, '# synthetic: generated by tools/bsp2lights.py from SYNTHETIC.bsp\n'
                         '# x y z r g b intensity radius\n'
                         '1.0 2.0 3.0 0.2500 0.5000 1.0000 1200 4 style 11\n')

    def test_event_style_boundaries_and_invalid_values(self):
        text, _, errors = self.export([{'classname': 'worldspawn'}] +
                                     [self.light(style=style) for style in ('1', '32', '63', '64', '-1', 'bad')],
                                     '--events')
        rows = self.rows(text)
        self.assertEqual([r.split(' style ')[1] for r in rows[:3]], ['1', '32', '63'])
        self.assertTrue(all('style' not in row for row in rows[3:]))
        self.assertEqual(errors.count('no event mapping'), 3)
        self.assertIn('paired event-lighting QindieGL', text)

    def test_startoff_appended_after_old_lights_and_sun(self):
        entities = [{'classname': 'worldspawn', '_sun_light': '400', '_sun_angle': '0 -90'},
                    self.light(origin='10 0 0', style='32', spawnflags='1'),
                    self.light(origin='20 0 0'),
                    self.light(origin='30 0 0', spawnflags='1', style='63'),
                    self.light(origin='40 0 0', style='2')]
        old, _, _ = self.export(entities)
        events, summary, _ = self.export(entities, '--events')
        old_rows, event_rows = self.rows(old), self.rows(events)
        self.assertEqual(old_rows, event_rows[:len(old_rows)])
        self.assertTrue(event_rows[len(old_rows) - 1].startswith('sun '))
        self.assertTrue(event_rows[-2].endswith('style 32 startoff'))
        self.assertTrue(event_rows[-1].endswith('style 63 startoff'))
        self.assertIn('2 start-off retained', summary)

    def test_unmapped_startoff_retained_and_reported(self):
        text, _, errors = self.export([{'classname': 'worldspawn'},
                                      self.light(spawnflags='1', targetname='switch'),
                                      self.light(spawnflags='1', style='64')], '--events')
        self.assertEqual(len(self.rows(text)), 2)
        self.assertTrue(all(row.endswith(' startoff') and 'style' not in row for row in self.rows(text)))
        self.assertEqual(errors.count('retained with off fallback'), 2)

    def test_spotlight_and_strongest_sun_preserved(self):
        entities = [{'classname': 'worldspawn', '_sun_light': '200', '_sun_angle': '0 -90',
                     '_sun2_light': '600', '_sun2_angle': '90 0', '_sun2_color': '0.5 0.25 1'},
                    {'classname': 'info_null', 'targetname': 'aim', 'origin': '4 6 3'},
                    self.light(target='aim', _cone='120', style='32', spawnflags='1'),
                    self.light(angle='-2', _cone='1')]
        text, _, _ = self.export(entities, '--events')
        rows = self.rows(text)
        self.assertTrue(rows[0].endswith('0.0000 0.0000 -1.0000 5'))
        self.assertEqual(rows[1], 'sun -0.0000 -1.0000 0.0000 0.5000 0.2500 1.0000 3 2')
        self.assertTrue(rows[2].endswith('3.0000 4.0000 0.0000 90 style 32 startoff'))

    def test_unknown_or_conflicting_options_fail_before_writing(self):
        for options in [('--legacy', '--events'), ('--event', '--legacy'), ('--unknown',)]:
            with self.subTest(options=options), redirect_stderr(io.StringIO()):
                with self.assertRaises(SystemExit) as error:
                    bsp2lights.main([*options, str(self.root / 'out'), str(self.bsp)])
                self.assertEqual(error.exception.code, 2)
                self.assertFalse((self.root / 'out').exists())

    def test_api_rejects_conflicting_modes(self):
        with self.assertRaisesRegex(ValueError, 'cannot be combined'):
            bsp2lights.export_maps([], self.root / 'out', legacy=True, events=True)


if __name__ == '__main__':
    unittest.main()
