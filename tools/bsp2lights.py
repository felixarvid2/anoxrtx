#!/usr/bin/env python3
"""Write QindieGL maplights files from Anachronox maps.

usage: bsp2lights.py [--legacy | --events] OUTDIR MAP.bsp...

Line format (read by QindieGL's `maplights` option, see QindieGL rmx_maplights.cpp):
    x y z r g b intensity radius [dx dy dz cone_degrees] [style N] [startoff]
    sun dx dy dz r g b intensity angle_degrees
x y z: light origin in game units; r g b: _color (0..1, default white); radius: sphere radius in game
units; the optional last four fields make a spotlight (direction + cone angle).

Files start with a `format raw` line: intensity is the BSP `light` value and radius is 0, and QindieGL
computes both from the [maplights.global] / [maplights.<map>] sections of anox_customise.ini
(scale, exponent, ref, radius, sun_scale; QindieGL reloads when that file or a .lights file changes):
  intensity = scale * ref * (light / ref) ^ exponent,   radius = radius
--legacy writes precomputed values instead (for QindieGL builds before maplights-tune), using the
defaults exponent 2, ref 300, radius 4:

Intensity (calibrated against the maps' baked lightmaps with tools/lightcal.py, low confidence):
  intensity = light^2 / L_REF (L_REF = 300, so a default 300 light keeps intensity 300)
  The measured reach is ~0.4-0.9 x `light`; an inverse-square Remix light reaches a fixed brightness at a
  distance proportional to sqrt(intensity), so intensity ~ light^2 keeps the relative reach.
  `cap` showed no effect in the lightmaps and `falloff` no consistent one, so both are ignored.
  spotlight when `_cone` is set and a direction is known: towards the `target` entity, or from
  `angle` (yaw; -1 up, -2 down) / `angles` (pitch yaw roll); cone angle = _cone, clamped to 5..90.
Only `light` entities are written; lights with spawnflags & 1 (START_OFF) are skipped, `style` 1..11
(Quake 2 flicker/pulse styles) is written so QindieGL animates it. A `sun` line comes from worldspawn
_sun_angle ("yaw pitch", pitch < 0 = sun above the horizon), _sun_color, _sun_light (ArghRad keys; the
stronger of _sun and _sun2): direction = towards the sun (what the Remix API's distant light expects; the
opposite left the ground unlit, comhills 2026-10-26), intensity = _sun_light / SUN_DIV.
Global brightness: maplights_scale in QindieGL.ini, or `scale` in anox_customise.ini.

--events requires the paired event-lighting QindieGL wrapper. It preserves styles 1..63 and appends
START_OFF lights after all existing light/sun rows, with a startoff marker. Existing override indices
are preserved. Unmapped START_OFF lights remain off when no valid game style is available. Older
files remain supported by the new wrapper; see docs/event-light-format.md.

Put the files in <Anachronox>/rtx-remix/maplights/.
"""
import argparse, importlib.util, math, os, sys

here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('bspinfo', os.path.join(here, 'bspinfo.py'))
bspinfo = importlib.util.module_from_spec(spec); spec.loader.exec_module(bspinfo)

RADIUS = 4.0
L_REF = 300.0
SUN_DIV = 200.0
SUN_ANGLE = 2.0


def angles_dir(keys):
    """Quake 2 angle conventions -> unit direction, or None"""
    if 'angles' in keys:
        try:
            pitch, yaw = [float(x) for x in keys['angles'].split()[:2]]
        except ValueError:
            return None
    elif 'angle' in keys:
        try:
            yaw = float(keys['angle'])
        except ValueError:
            return None
        if yaw == -1: return (0.0, 0.0, 1.0)
        if yaw == -2: return (0.0, 0.0, -1.0)
        pitch = 0.0
    else:
        return None
    p, y = math.radians(pitch), math.radians(yaw)
    return (math.cos(p) * math.cos(y), math.cos(p) * math.sin(y), -math.sin(p))


def fnum(s, default):
    try:
        return float(s)
    except (TypeError, ValueError):
        return default


def export_maps(paths, out, legacy=False, events=False):
    """Export maps without changing default rows or legacy override indices."""
    if legacy and events:
        raise ValueError('--events cannot be combined with --legacy')
    os.makedirs(out, exist_ok=True)
    total = 0; spots = 0; animated = 0; startoff = 0; suns = 0
    for path in paths:
        info = bspinfo.info(path)
        name = os.path.splitext(info['map'])[0].lower()
        rows = ['# %s: generated by tools/bsp2lights.py from %s' % (name, info['map']),
                '# x y z r g b intensity radius' + ('' if legacy else '   (intensity = BSP light, radius 0 = from the ini)')]
        if not legacy:
            rows.append('format raw')
        if events:
            rows.append('# events: requires paired event-lighting QindieGL; old files remain supported')
            rows.append('# START_OFF rows appended to preserve existing override indices; unmapped stay off')
        header_count = len(rows)
        off_rows = []
        _, ents, _ = bspinfo.load(path)
        named = {e['targetname']: e for e in ents if e.get('targetname')}
        for l in info['lights']:
            if l['classname'] != 'light':
                continue
            k = l['keys']; x, y, z = l['origin']; r, g, b = l['color']
            if legacy:
                inten, rad = round(l['light'] * l['light'] / L_REF, 2), RADIUS
            else:
                inten, rad = l['light'], 0
            row = '%.1f %.1f %.1f %.4f %.4f %.4f %g %g' % (x, y, z, r, g, b, inten, rad)
            cone = fnum(k.get('_cone') or k.get('-cone'), 0.0)
            if cone > 0:
                d = None
                t = named.get(k.get('target', ''))
                if t:
                    tx, ty, tz = bspinfo.vec(t.get('origin'))
                    d = (tx - x, ty - y, tz - z)
                else:
                    d = angles_dir(k)
                if d and any(abs(c) > 1e-6 for c in d):
                    row += ' %.4f %.4f %.4f %g' % (d[0], d[1], d[2], min(90.0, max(5.0, cone)))
                    spots += 1
            try:
                st = int(k.get('style', '0') or 0)
                valid_style = 0 <= st <= 63
            except ValueError:
                st = 0
                valid_style = False
            if events and not valid_style:
                print('%s: light at %s has invalid style %r; no event mapping' %
                      (info['map'], k.get('origin', '0 0 0'), k.get('style')), file=sys.stderr)
            if 1 <= st <= (63 if events else 11):
                row += ' style %d' % st; animated += 1
            if int(fnum(k.get('spawnflags'), 0)) & 1:
                startoff += 1
                if events:
                    off_rows.append(row + ' startoff')
                    if not 1 <= st <= 63:
                        print('%s: START_OFF light at %s has no usable event style; '
                              'retained with off fallback' %
                              (info['map'], k.get('origin', '0 0 0')), file=sys.stderr)
                continue
            rows.append(row)
        w = ents[0] if ents else {}
        best = None
        for pre in ('_sun', '_sun2'):
            if pre + '_light' in w and pre + '_angle' in w:
                L = fnum(w[pre + '_light'], 0.0)
                try:
                    yaw, pitch = [float(v) for v in w[pre + '_angle'].split()[:2]]
                except ValueError:
                    continue
                if best is None or L > best[0]:
                    best = (L, yaw, pitch, bspinfo.vec(w.get(pre + '_color'), (1, 1, 1)))
        if best and best[0] > 0:
            L, yaw, pitch, col = best
            p_, y_ = math.radians(pitch), math.radians(yaw)
            fwd = (math.cos(p_) * math.cos(y_), math.cos(p_) * math.sin(y_), -math.sin(p_))   # towards the sun
            rows.append('sun %.4f %.4f %.4f %.4f %.4f %.4f %g %g' % (fwd[0], fwd[1], fwd[2], col[0], col[1], col[2],
                                                                  round(L / SUN_DIV, 3), SUN_ANGLE))
            suns += 1
        rows.extend(off_rows)
        with open(os.path.join(out, name + '.lights'), 'w') as f:
            f.write('\n'.join(rows) + '\n')
        total += len(rows) - header_count
    print('%d maps, %d lights (%d spotlights, %d animated, %d start-off %s, %d suns) -> %s' %
          (len(paths), total, spots, animated, startoff, 'retained' if events else 'skipped', suns, out))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter,
                                     allow_abbrev=False)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--legacy', action='store_true')
    mode.add_argument('--events', action='store_true')
    parser.add_argument('outdir')
    parser.add_argument('maps', nargs='+')
    args = parser.parse_args(argv)
    export_maps(args.maps, args.outdir, legacy=args.legacy, events=args.events)


if __name__ == '__main__':
    main()
