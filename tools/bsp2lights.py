#!/usr/bin/env python3
"""Write QindieGL maplights files from Anachronox maps.

usage: bsp2lights.py OUTDIR MAP.bsp...      -> OUTDIR/<map>.lights  (one per map)

Line format (read by QindieGL's `maplights` option, see QindieGL rmx_maplights.cpp):
    x y z r g b intensity radius
x y z: light origin in game units; r g b: _color (0..1, default white); intensity: the entity's
`light` value (default 300; tune globally with maplights_scale in QindieGL.ini); radius: sphere
radius in game units. Only `light` entities are written.

Put the files in <Anachronox>/rtx-remix/maplights/.
"""
import importlib.util, os, sys

here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('bspinfo', os.path.join(here, 'bspinfo.py'))
bspinfo = importlib.util.module_from_spec(spec); spec.loader.exec_module(bspinfo)

RADIUS = 4.0


def main():
    if len(sys.argv) < 3:
        print(__doc__); sys.exit(1)
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    total = 0
    for path in sys.argv[2:]:
        info = bspinfo.info(path)
        name = os.path.splitext(info['map'])[0].lower()
        rows = ['# %s: generated by tools/bsp2lights.py from %s' % (name, info['map']),
                '# x y z r g b intensity radius']
        for l in info['lights']:
            if l['classname'] != 'light':
                continue
            x, y, z = l['origin']; r, g, b = l['color']
            rows.append('%.1f %.1f %.1f %.4f %.4f %.4f %g %g' % (x, y, z, r, g, b, l['light'], RADIUS))
        with open(os.path.join(out, name + '.lights'), 'w') as f:
            f.write('\n'.join(rows) + '\n')
        total += len(rows) - 2
    print('%d maps, %d lights -> %s' % (len(sys.argv) - 2, total, out))


if __name__ == '__main__':
    main()
