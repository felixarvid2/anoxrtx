#!/usr/bin/env python3
"""Turn the light entities of an Anachronox map (.bsp) into RTX Remix lights (a USDA layer).

usage: bsp2usd.py MAP.bsp OUT.usda [--scale K] [--radius R] [--min-light L]

Each `light` entity becomes a SphereLight under /RootNode/lights, in game units (the same space as
Remix captures; rtx.zUp = True). Anachronox keys used: origin, light (default 300), _color (0..1).
Intensity = K * light (default K = 0.5); radius R game units (default 4). Lights weaker than L are skipped.
`falloff`, `cap` and `_cone` are Anachronox extensions; they are written as custom attributes
(anox:falloff, anox:cap, anox:cone) so they can be used for tuning later, but do not change the light.

NOTE (verified in game + dxvk-remix 1.5.2 rtx_mod_usd.cpp): Remix only reads children of
/RootNode/lights as *replacements of game lights* (prims named light_<hash>); free-standing lights there
are ignored. To use these lights they have to be parented to a mesh replacement
(/RootNode/meshes/mesh_<hash>, like vinevi1's mod.usda does), e.g. a world mesh of the map taken from a
Remix capture (rtx.captureHotKey, default CTRL+SHIFT+Q; rtx.captureShowMenuOnHotkey = False). World
geometry is drawn with an identity model matrix, so world coordinates can be used as the child translate.
"""
import argparse, importlib.util, os, re

here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('bspinfo', os.path.join(here, 'bspinfo.py'))
bspinfo = importlib.util.module_from_spec(spec); spec.loader.exec_module(bspinfo)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('bsp'); ap.add_argument('out')
    ap.add_argument('--scale', type=float, default=0.5)
    ap.add_argument('--radius', type=float, default=4.0)
    ap.add_argument('--min-light', type=float, default=0.0)
    a = ap.parse_args()

    info = bspinfo.info(a.bsp)
    mapname = re.sub(r'\W', '_', os.path.splitext(info['map'])[0])
    out = ['#usda 1.0', '(', '    customLayerData = {',
           '        string anox_source = "%s"' % info['map'],
           '        string anox_note = "generated by tools/bsp2usd.py --scale %g --radius %g"' % (a.scale, a.radius),
           '    }', '    metersPerUnit = 1', '    upAxis = "Y"', ')', '',
           'over "RootNode"', '{', '    over "lights"', '    {']
    n = 0
    for i, l in enumerate(info['lights']):
        if l['classname'] != 'light' or l['light'] < a.min_light:
            continue
        x, y, z = l['origin']; r, g, b = l['color']; k = l['keys']
        out += ['        def SphereLight "anox_%s_%04d"' % (mapname, i), '        {',
                '            color3f inputs:color = (%.4f, %.4f, %.4f)' % (r, g, b),
                '            float inputs:intensity = %.2f' % (a.scale * l['light']),
                '            float inputs:radius = %.2f' % a.radius,
                '            double3 xformOp:translate = (%.2f, %.2f, %.2f)' % (x, y, z),
                '            uniform token[] xformOpOrder = ["xformOp:translate"]']
        for key, attr in (('falloff', 'anox:falloff'), ('cap', 'anox:cap'), ('_cone', 'anox:cone')):
            if key in k:
                try:
                    out.append('            custom float %s = %g' % (attr, float(k[key])))
                except ValueError:
                    pass
        out += ['        }', '']
        n += 1
    out += ['    }', '}', '']
    with open(a.out, 'w') as f:
        f.write('\n'.join(out))
    print('%s: %d lights -> %s' % (info['map'], n, a.out))


if __name__ == '__main__':
    main()
